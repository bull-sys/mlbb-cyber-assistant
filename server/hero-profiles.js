export function validateHeroProfiles(profiles = heroProfiles) {
  const errors = [];
  const ids = new Set();

  for (const hero of profiles) {
    if (!hero.id) {
      errors.push("Missing hero ID");
      continue;
    }

    if (ids.has(hero.id)) {
      errors.push("Duplicate ID: " + hero.id);
    }

    ids.add(hero.id);

    if (!hero.names?.ru) {
      errors.push(hero.id + ": missing Russian name");
    }

    if (!hero.matchups?.strongAgainst ||
        !hero.matchups?.weakAgainst) {
      errors.push(hero.id + ": missing matchup data");
    }

    for (const field of ["mechanics", "strengths", "weaknesses", "synergies", "itemNotes"]) {
      if (!Array.isArray(hero[field]) || hero[field].length === 0) {
        errors.push(hero.id + ": empty " + field);
      }
    }

    if (!hero.teamfight?.preferredPlan) {
      errors.push(hero.id + ": missing teamfight plan");
    }

    if (!Array.isArray(hero.sources) || hero.sources.length === 0) {
      errors.push(hero.id + ": missing sources");
    }
  }

  return {
    ok: errors.length === 0,
    count: profiles.length,
    errors
  };
}
